import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { deflateSync, inflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import Ajv from 'ajv';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';

// JSON frontmatter is YAML-compatible. Root documents own the declarations.
async function label(file) {
  const text = await readFile(file, 'utf8');
  return { text, data: JSON.parse(text.split('---')[1]) };
}
const app = await label('APP_FACTS.md');
const features = await label('FEATURE_FACTS.md');
const schema = async (name) => JSON.parse(await readFile(`facts/schema/${name}.schema.json`, 'utf8'));
const appValidator = addFormats(new Ajv({ allErrors: true })).compile(await schema('app-facts'));
const featureAjv = addFormats(new Ajv2020({ allErrors: true, strict: false }));
featureAjv.addSchema(await schema('common'));
const featureValidator = featureAjv.compile(await schema('feature-facts-label'));
for (const [validate, data] of [[appValidator, app.data], [featureValidator, features.data]]) {
  if (!validate(data)) throw new Error(JSON.stringify(validate.errors));
}
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]));
  return value;
}
const { generated, ...projection } = features.data;
const fingerprint = createHash('sha256').update(JSON.stringify(canonical(projection))).digest('hex');
if (fingerprint !== generated.projection_fingerprint) throw new Error('FeatureFacts fingerprint is stale. Recalculate it after reviewing declaration changes.');
const payload = { v: 1, name: app.data.name, type: app.data.type, status: app.data.status,
  license: app.data.license, stack: app.data.stack,
  deps: app.data.key_dependencies.map((item) => ({ n: item.name, p: item.purpose, e: item.registry })),
  svc: app.data.services.map((item) => ({ n: item.name, r: item.role })), build: app.data.build, homepage: app.data.homepage };
const encoded = deflateSync(Buffer.from(JSON.stringify(payload)), { level: 9 }).toString('base64url');
if (JSON.parse(inflateSync(Buffer.from(encoded, 'base64url')).toString()).name !== 'Taskwatch') throw new Error('AppFacts viewer round trip failed');
const appFactsUrl = `https://appfacts.dev/v#af1.${encoded}`;
await mkdir('static/facts', { recursive: true });
for (const [name, item] of [['app', app], ['features', features]]) {
  await writeFile(`static/facts/${name}.json`, JSON.stringify(item.data, null, 2) + '\n');
  await writeFile(`static/facts/${name}.md`, item.text);
}
await writeFile('src/lib/facts.ts', `// Generated by scripts/facts.mjs from root xFacts declarations.\nexport const appFactsUrl = ${JSON.stringify(appFactsUrl)};\nexport const featureFacts = ${JSON.stringify(features.data, null, 2)};\n`);
console.log('AppFacts schema/viewer and standalone FeatureFacts schema/fingerprint verified.');
